const CANDIDATE_BOUNDARY_GATE_MS = 20;
const MARKER_WINDOW_MS = 10;
const FINE_RECHECK_WINDOW_MS = 2;
const PREFERRED_MIME_TYPES = Object.freeze([
  'audio/webm;codecs=opus',
  'audio/webm'
]);

export async function runWebmContinuitySpike({ durationMs = 65_000, rotationMs = 60_000 } = {}) {
  if (typeof MediaRecorder !== 'function') throw new Error('MediaRecorder unavailable');
  const mimeType = PREFERRED_MIME_TYPES.find((value) => MediaRecorder.isTypeSupported(value)) || '';
  const continuous = await captureScenario({ name: 'continuous-slices', durationMs, rotationMs: null, mimeType });
  const rotated = await captureScenario({ name: 'rotated-containers', durationMs, rotationMs, mimeType });
  const rotationPenaltyMs = rotated.timestampDriftMs - continuous.timestampDriftMs;
  const absolutePenaltyMs = Math.abs(rotationPenaltyMs);
  const fineUncertaintyMs = FINE_RECHECK_WINDOW_MS;
  const comparisonStatus = absolutePenaltyMs >= CANDIDATE_BOUNDARY_GATE_MS - fineUncertaintyMs
    && absolutePenaltyMs <= CANDIDATE_BOUNDARY_GATE_MS + fineUncertaintyMs
    ? 'MEASUREMENT_UNCERTAIN'
    : absolutePenaltyMs <= CANDIDATE_BOUNDARY_GATE_MS ? 'PASS' : 'FAIL';
  const result = {
    schemaVersion: 'webm-continuity-spike/v1',
    measuredAt: new Date().toISOString(),
    userAgent: navigator.userAgent,
    support: {
      requestedMimeType: mimeType || null,
      mediaRecorder: true,
      audioContext: typeof (window.AudioContext || window.webkitAudioContext) === 'function'
    },
    method: {
      sampleRate: continuous.sampleRate,
      source: 'deterministic multi-tone PCM generated by ScriptProcessorNode',
      markerWindowMs: MARKER_WINDOW_MS,
      fineRecheckWindowMs: FINE_RECHECK_WINDOW_MS,
      candidateBoundaryGateMs: CANDIDATE_BOUNDARY_GATE_MS,
      interpretation: 'Passing is only this experiment candidate gate; it does not prove zero audible gap.'
    },
    scenarios: { continuous, rotated },
    comparison: {
      rotationPenaltyMs,
      fineMeasurementResolutionMs: 1000 / continuous.sampleRate,
      uncertaintyWindowMs: fineUncertaintyMs,
      candidateStatus: comparisonStatus,
      interpretation: 'Difference between rotated and continuous decoded-vs-capture drift; PASS is not proof of zero audible gap.'
    }
  };
  globalThis.__webmSpikeResult = result;
  return result;
}

async function captureScenario({ name, durationMs, rotationMs, mimeType }) {
  const AudioContextImpl = window.AudioContext || window.webkitAudioContext;
  const audioContext = new AudioContextImpl({ sampleRate: 48_000 });
  const destination = audioContext.createMediaStreamDestination();
  const processor = audioContext.createScriptProcessor(1024, 0, 1);
  let generatedSamples = 0;
  processor.onaudioprocess = (event) => {
    const output = event.outputBuffer.getChannelData(0);
    for (let index = 0; index < output.length; index += 1) {
      const sampleIndex = generatedSamples + index;
      const time = sampleIndex / audioContext.sampleRate;
      const marker = Math.floor(time * 100) % 8;
      output[index] = 0.24 * Math.sin(2 * Math.PI * (440 + marker * 37) * time)
        + 0.08 * Math.sin(2 * Math.PI * 997 * time);
    }
    generatedSamples += output.length;
  };
  processor.connect(destination);
  await audioContext.resume();

  const containers = [];
  const recorderEvents = [];
  let active = null;
  let recorderInstances = 0;
  let mockProviderGeneration = 0;
  let recorderRestartsAtProviderRollover = 0;
  const captureSampleNow = () => Math.round(audioContext.currentTime * audioContext.sampleRate);

  const startContainer = () => {
    const recorder = new MediaRecorder(destination.stream, mimeType ? { mimeType } : undefined);
    recorderInstances += 1;
    const container = {
      index: containers.length,
      chunks: [],
      captureStartSample: captureSampleNow(),
      captureStopSample: null,
      wallStartedAt: performance.now(),
      wallStoppedAt: null,
      actualMimeType: recorder.mimeType || null
    };
    containers.push(container);
    recorder.ondataavailable = (event) => {
      if (event.data?.size > 0) container.chunks.push(event.data);
    };
    recorderEvents.push({ type: 'start', container: container.index, sample: captureSampleNow(), wallMs: performance.now() });
    recorder.start(1000);
    active = recorder;
  };

  const stopContainer = () => new Promise((resolve) => {
    const recorder = active;
    const container = containers.at(-1);
    if (!recorder || recorder.state === 'inactive') return resolve();
    recorder.addEventListener('stop', () => {
      container.captureStopSample = captureSampleNow();
      container.wallStoppedAt = performance.now();
      recorderEvents.push({ type: 'stop', container: container.index, sample: captureSampleNow(), wallMs: performance.now() });
      resolve();
    }, { once: true });
    recorder.stop();
  });

  startContainer();
  const startedAt = performance.now();
  const providerRolloverAt = Math.min(durationMs * 0.35, Math.max(1000, durationMs - 1500));
  const pauseAt = Math.min(durationMs * 0.55, Math.max(1500, durationMs - 1000));
  const pauseDurationMs = Math.min(500, Math.max(200, durationMs * 0.06));
  const providerTimer = setTimeout(() => {
    const before = recorderInstances;
    mockProviderGeneration += 1;
    recorderRestartsAtProviderRollover += recorderInstances - before;
    recorderEvents.push({ type: 'mock-provider-rollover', generation: mockProviderGeneration, sample: captureSampleNow(), wallMs: performance.now() });
  }, providerRolloverAt);
  const pauseTimer = setTimeout(() => {
    if (active?.state === 'recording') {
      active.pause();
      recorderEvents.push({ type: 'pause', container: containers.length - 1, sample: captureSampleNow(), wallMs: performance.now() });
      setTimeout(() => {
        if (active?.state === 'paused') {
          active.resume();
          recorderEvents.push({ type: 'resume', container: containers.length - 1, sample: captureSampleNow(), wallMs: performance.now() });
        }
      }, pauseDurationMs);
    }
  }, pauseAt);

  if (rotationMs && rotationMs < durationMs) {
    await delay(rotationMs);
    await stopContainer();
    startContainer();
    await delay(Math.max(0, durationMs - (performance.now() - startedAt)));
  } else {
    await delay(durationMs);
  }
  clearTimeout(providerTimer);
  clearTimeout(pauseTimer);
  await stopContainer();
  const wallDurationMs = performance.now() - startedAt;
  processor.disconnect();
  destination.stream.getTracks().forEach((track) => track.stop());

  const decodedContainers = [];
  for (const container of containers) {
    decodedContainers.push(await decodeBlob(audioContext, new Blob(container.chunks, { type: container.actualMimeType || mimeType })));
  }
  const slices = containers.flatMap((container) => container.chunks);
  const sliceDecode = await decodeSelectedSlices(audioContext, slices);
  const prefixDecode = await decodeSelectedPrefixes(audioContext, slices, mimeType);
  const captureSamples = containers.reduce((sum, container) => sum + Math.max(0, container.captureStopSample - container.captureStartSample), 0)
    - pausedCaptureSamples(recorderEvents);
  const decodedSamples = decodedContainers.reduce((sum, decoded) => sum + (decoded.sampleCount || 0), 0);
  const sampleRate = decodedContainers.find((item) => item.sampleRate)?.sampleRate || audioContext.sampleRate;
  const decodedDurationMs = decodedSamples / sampleRate * 1000;
  const captureDurationMs = captureSamples / audioContext.sampleRate * 1000;
  const boundaryGapMs = containers.length > 1
    ? (containers[1].captureStartSample - containers[0].captureStopSample) / audioContext.sampleRate * 1000
    : null;
  const boundaryDeltaMs = containers.length > 1 ? decodedDurationMs - captureDurationMs : null;
  const absoluteBoundaryDeltaMs = boundaryDeltaMs === null ? null : Math.abs(boundaryDeltaMs);
  const nearGate = absoluteBoundaryDeltaMs !== null
    && absoluteBoundaryDeltaMs >= CANDIDATE_BOUNDARY_GATE_MS - FINE_RECHECK_WINDOW_MS
    && absoluteBoundaryDeltaMs <= CANDIDATE_BOUNDARY_GATE_MS + FINE_RECHECK_WINDOW_MS;
  const candidateStatus = boundaryDeltaMs === null
    ? 'NOT_APPLICABLE'
    : nearGate
      ? 'MEASUREMENT_UNCERTAIN_FINE_RECHECK_REQUIRED'
      : absoluteBoundaryDeltaMs <= CANDIDATE_BOUNDARY_GATE_MS ? 'PASS' : 'FAIL';

  await audioContext.close();
  return {
    name,
    requestedDurationMs: durationMs,
    rotationMs,
    sampleRate,
    wallDurationMs,
    captureDurationMs,
    decodedDurationMs,
    decodedSampleCount: decodedSamples,
    captureSampleCount: captureSamples,
    timestampDriftMs: decodedDurationMs - captureDurationMs,
    boundaryGapMs,
    boundaryDeltaMs,
    candidateStatus,
    analysisResolution: nearGate
      ? `${FINE_RECHECK_WINDOW_MS}ms fine uncertainty window; result remains uncertain`
      : `${1000 / sampleRate}ms decoded/audio-clock sample resolution; ${MARKER_WINDOW_MS}ms content marker window`,
    recorderInstances,
    mockProviderGeneration,
    recorderRestartsAtProviderRollover,
    actualMimeTypes: [...new Set(containers.map((container) => container.actualMimeType))],
    chunksPerContainer: containers.map((container) => container.chunks.length),
    containerDecode: decodedContainers,
    selectedSliceDecode: sliceDecode,
    selectedPrefixDecode: prefixDecode,
    pauseContinue: summarizePause(recorderEvents),
    events: recorderEvents
  };
}

async function decodeSelectedSlices(audioContext, slices) {
  const indexes = selectedIndexes(slices.length);
  return Promise.all(indexes.map(async (index) => ({ index, ...(await decodeBlob(audioContext, slices[index])) })));
}

async function decodeSelectedPrefixes(audioContext, slices, mimeType) {
  const indexes = selectedIndexes(slices.length);
  return Promise.all(indexes.map(async (index) => ({
    throughIndex: index,
    ...(await decodeBlob(audioContext, new Blob(slices.slice(0, index + 1), { type: mimeType })))
  })));
}

async function decodeBlob(audioContext, blob) {
  try {
    const buffer = await audioContext.decodeAudioData(await blob.arrayBuffer());
    return {
      ok: true,
      byteSize: blob.size,
      sampleCount: buffer.length,
      sampleRate: buffer.sampleRate,
      durationMs: buffer.duration * 1000,
      channels: buffer.numberOfChannels
    };
  } catch (error) {
    return { ok: false, byteSize: blob.size, error: error?.name || 'decode_failed' };
  }
}

function selectedIndexes(length) {
  return [...new Set([0, Math.floor((length - 1) / 2), length - 1].filter((index) => index >= 0))];
}

function summarizePause(events) {
  const pause = events.find((event) => event.type === 'pause');
  const resume = events.find((event) => event.type === 'resume');
  return {
    exercised: Boolean(pause && resume),
    captureTimelinePauseMs: pause && resume ? (resume.sample - pause.sample) / 48_000 * 1000 : null,
    wallPauseMs: pause && resume ? resume.wallMs - pause.wallMs : null
  };
}

function pausedCaptureSamples(events) {
  let pausedAt = null;
  let pausedSamples = 0;
  for (const event of events) {
    if (event.type === 'pause') pausedAt = event;
    if (event.type === 'resume' && pausedAt?.container === event.container) {
      pausedSamples += Math.max(0, event.sample - pausedAt.sample);
      pausedAt = null;
    }
  }
  return pausedSamples;
}

function delay(ms) { return new Promise((resolve) => setTimeout(resolve, ms)); }

const output = document.querySelector('#output');
const download = document.querySelector('#download');
let lastResult = null;
async function run(options) {
  output.textContent = 'Running…';
  document.querySelectorAll('button').forEach((button) => { button.disabled = true; });
  try {
    lastResult = await runWebmContinuitySpike(options);
    output.textContent = JSON.stringify(lastResult, null, 2);
    download.disabled = false;
  } catch (error) {
    output.textContent = JSON.stringify({ status: 'FAILED_TO_RUN', error: error?.message || String(error) }, null, 2);
  } finally {
    document.querySelector('#quick').disabled = false;
    document.querySelector('#full').disabled = false;
  }
}
document.querySelector('#quick').addEventListener('click', () => run({ durationMs: 8_000, rotationMs: 4_000 }));
document.querySelector('#full').addEventListener('click', () => run({ durationMs: 65_000, rotationMs: 60_000 }));
download.addEventListener('click', () => {
  if (!lastResult) return;
  const anchor = document.createElement('a');
  anchor.href = URL.createObjectURL(new Blob([JSON.stringify(lastResult, null, 2)], { type: 'application/json' }));
  anchor.download = `webm-continuity-${Date.now()}.json`;
  anchor.click();
  URL.revokeObjectURL(anchor.href);
});
